create table if not exists public.notes (
  id          bigint generated by default as identity primary key,
  body        text        not null check (char_length(body) between 1 and 2000),
  author      text        not null default 'her' check (author in ('her','him')),
  created_at  timestamptz not null default now()
);

create index if not exists notes_created_at_idx on public.notes (created_at desc);

-- ------------------------------------------------------------
--  Row level security
--  This is a tiny private two-person app, so the rule is simple:
--  anyone holding the link may read and write notes. Nothing else
--  in your project is exposed, and there are no user accounts.
--  If you want it stricter, see the note at the bottom.
-- ------------------------------------------------------------
alter table public.notes enable row level security;

drop policy if exists "her notes are readable" on public.notes;
create policy "her notes are readable"
  on public.notes for select
  to anon
  using (true);

drop policy if exists "her notes can be left" on public.notes;
create policy "her notes can be left"
  on public.notes for insert
  to anon
  with check (author = 'her' or author = 'him');

-- nothing can be edited or deleted from the browser by default
revoke update, delete on public.notes from anon;

