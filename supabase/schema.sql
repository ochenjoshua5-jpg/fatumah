-- ------------------------------------------------------------
--  1. the hash: FNV-1a 32-bit, byte-identical to the JavaScript
--     implementation in index.html, so both agree on the answer
-- ------------------------------------------------------------
create or replace function public.fnv1a(txt text)
returns bigint
language plpgsql
immutable
as $$
declare
  h bigint := 2166136261;
  i int;
  c bigint;
begin
  for i in 1..length(txt) loop
    c := ascii(substr(txt, i, 1));
    h := ((h # c) * 16777619) % 4294967296;
  end loop;
  return h;
end;
$$;

-- ------------------------------------------------------------
--  2. where the right answer actually lives
--
--     RLS on, and NO policies at all. The browser role cannot
--     read this table, by design. It exists so the password is
--     stored properly instead of sitting in a public file.
-- ------------------------------------------------------------
create table if not exists public.closet_keys (
  song_id   text primary key,
  digest    bigint not null,
  is_answer boolean not null default false
);

alter table public.closet_keys enable row level security;
revoke all on public.closet_keys from anon, authenticated;

-- The four songs, with their fingerprints.
-- Salt: 'kc-2026-fatumah-9f3a' — must match LOCK.salt in index.html.
-- exactly one row has is_answer = true.
insert into public.closet_keys (song_id, digest, is_answer) values
  ('please-please-please', 1039208479, false),
  ('rich-flex',            3192522019, false),
  ('knife-talk',           1525856033, false),
  ('these-walls',          4282841718, true)
on conflict (song_id) do update
  set digest = excluded.digest,
      is_answer = excluded.is_answer;

-- ------------------------------------------------------------
--  3. the only thing the browser is allowed to do: ask
--
--     security definer so the function can read the locked table,
--     but it only ever answers true or false. A caller learns
--     nothing except whether the song they already tried is the
--     right one — which is exactly what tapping a card tells them.
-- ------------------------------------------------------------
create or replace function public.closet_unlock(attempt text)
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.closet_keys
    where is_answer = true
      and digest = public.fnv1a(coalesce(attempt,'') || 'kc-2026-fatumah-9f3a')
  );
$$;

revoke all on function public.closet_unlock(text) from public, anon, authenticated;
grant execute on function public.closet_unlock(text) to anon, authenticated;

-- ------------------------------------------------------------
--  4. a quiet audit trail, so you can see if anyone tried
--     (readable by you in the dashboard; not readable by her)
-- ------------------------------------------------------------
create table if not exists public.lock_attempts (
  id bigint generated by default as identity primary key,
  song_id text,
  ok boolean not null default false,
  at timestamptz not null default now()
);

alter table public.lock_attempts enable row level security;
revoke all on public.lock_attempts from anon, authenticated;

drop policy if exists "attempts can be logged" on public.lock_attempts;
create policy "attempts can be logged"
  on public.lock_attempts for insert
  to anon
  with check (char_length(coalesce(song_id,'')) <= 60);

-- ------------------------------------------------------------
--  5. her write-back notes
-- ------------------------------------------------------------
create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  body text not null check (char_length(body) between 1 and 2000),
  author text not null default 'her' check (author in ('her','him')),
  created_at timestamptz not null default now()
);

create index if not exists notes_created_at_idx on public.notes (created_at desc);
alter table public.notes enable row level security;

drop policy if exists "notes readable" on public.notes;
create policy "notes readable" on public.notes for select to anon using (true);

drop policy if exists "notes writable" on public.notes;
create policy "notes writable" on public.notes for insert to anon
  with check (author in ('her','him'));

-- nothing in the browser can edit or erase her words
revoke update, delete on public.notes from anon;

-- ------------------------------------------------------------
--  6. how to change the song
--
--     1. compute the new fingerprint (the salt must match LOCK.salt):
--
--        select public.fnv1a('new-song-id' || 'kc-2026-fatumah-9f3a');
--
--     2. flip the flags — exactly one row may be true:
--
--        update public.closet_keys set is_answer = (song_id = 'new-song-id');
--
--     3. update the `songs` array and LOCK.digest in index.html to match,
--        bump CACHE in sw.js, redeploy.
--
--     Tip: a partial unique index stops you making two right answers.
-- ------------------------------------------------------------

create unique index if not exists closet_keys_one_answer
  on public.closet_keys (is_answer) where is_answer = true;

-- a friendly first row for the notes table, so you can see it working
insert into public.notes (body, author)
select 'this table works. now she can talk back. ♡', 'her'
where not exists (select 1 from public.notes);
